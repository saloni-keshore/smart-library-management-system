-- =========================================================================

BEGIN;

DROP FUNCTION IF EXISTS public.rpc_login_throttled(text);
DROP FUNCTION IF EXISTS public.rpc_clear_login_failures(text);
DROP FUNCTION IF EXISTS public.rpc_record_login_failure(text);

CREATE OR REPLACE FUNCTION public.rpc_record_login_failure(
  p_identifier text, p_client_key text DEFAULT ''
) RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  INSERT INTO login_failures (key) VALUES
    ('pair:' || left(coalesce(p_client_key, ''), 128) || '|' || left(lower(coalesce(p_identifier, '')), 200)),
    ('id:' || left(lower(coalesce(p_identifier, '')), 200));
$$;

REVOKE ALL ON FUNCTION public.rpc_record_login_failure(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.rpc_record_login_failure(text, text) TO anon;

COMMIT;

