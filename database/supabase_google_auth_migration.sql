-- Smart Library App - Google sign-in, Google-based account recovery, and
-- auth hardening (ADR-84/85/86)
--
-- Run this whole file once in the Supabase SQL Editor, on the TEST project
-- first, then on production. It is idempotent (safe to re-run).
--
-- What it does:
--
--   1. Google sign-in via Supabase Auth (ADR-84). admins gains
--      auth_user_id (the Supabase Auth user id a Google login produces),
--      google_email and has_password. Four new RPCs:
--        - rpc_google_login_lookup()   - who is this Google user? Called
--          with the user's OWN Supabase Auth access token, so Postgres
--          verifies the Google identity itself (auth.uid()); there is no
--          parameter a caller could forge.
--        - rpc_register_admin_google() - create a library for a Google
--          user that has none yet. Same identity source (auth.uid()).
--        - rpc_link_google()/rpc_unlink_google() - connect/disconnect
--          Google from Settings -> Security. Scoped by current_admin_id(),
--          i.e. only callable with a Flask-minted tenant JWT.
--      The name+mobile "forgot password" RPCs are DROPPED: anyone who knew
--      an admin's full name and mobile could reset their password (QA
--      audit 2026-10-03). Recovery is now "sign in with Google".
--
--   2. Logout actually revokes the session (ADR-85). admins gains
--      session_version; Flask puts it in every tenant JWT as the `sv`
--      claim, current_admin_id() refuses a JWT whose sv is stale, and
--      logout/password change bump it. Before this, a copied session
--      cookie kept working after logout.
--
--   3. Login throttle that works on Vercel (ADR-86). The old in-process
--      counter (utils/security.py rate_limited()) was per serverless
--      instance and keyed by IP only, so it both leaked attempts across
--      instances and locked out everyone behind one library Wi-Fi. Now
--      enforced inside rpc_login_lookup() itself (it is anon-callable, so
--      a Flask-only check could be skipped), counted in login_failures:
--      5 per IP+username and 20 per username, per 15 minutes.
--
--   4. Usernames are case-insensitive (TD-118): login matches
--      lower(username), registration rejects a case-variant duplicate,
--      and a unique index on lower(username) enforces it.


-- =========================================================================
-- 0. PRE-CHECK - run this SELECT on its own first. It must return 0 rows,
-- otherwise the unique index in section 1 will fail. If it returns rows,
-- rename one account of each pair before continuing.
-- =========================================================================
--
--   SELECT lower(username) AS username_lower, array_agg(admin_id) AS admin_ids
--   FROM admins
--   GROUP BY lower(username)
--   HAVING count(*) > 1;


-- =========================================================================
-- 1. Schema
-- =========================================================================

BEGIN;

ALTER TABLE admins ADD COLUMN IF NOT EXISTS auth_user_id uuid;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS google_email text;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS has_password boolean NOT NULL DEFAULT true;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS session_version integer NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS admins_auth_user_id_key ON admins (auth_user_id);
CREATE UNIQUE INDEX IF NOT EXISTS admins_username_lower_key ON admins (lower(username));

CREATE TABLE IF NOT EXISTS login_failures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL,
  failed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS login_failures_key_time_idx ON login_failures (key, failed_at);

-- No policies on purpose: only the SECURITY DEFINER throttle RPCs below
-- ever touch this table.
ALTER TABLE login_failures ENABLE ROW LEVEL SECURITY;

COMMIT;


-- =========================================================================
-- 2. Session revocation: current_admin_id() also checks session_version.
-- A JWT with no `sv` claim (offline scripts, tests) still passes - only
-- Flask can sign these JWTs, and Flask always includes sv for a logged-in
-- request.
-- =========================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.current_admin_id() RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public
AS $$
  SELECT a.admin_id
  FROM admins a
  WHERE a.admin_id = NULLIF(
          current_setting('request.jwt.claims', true)::json->>'admin_id',
          ''
        )::integer
    AND a.status = 'active'
    AND a.session_version = COALESCE(
          NULLIF(current_setting('request.jwt.claims', true)::json->>'sv', '')::integer,
          a.session_version
        )
$$;

-- Bumped on logout and on password change: every outstanding session for
-- this admin (this device's and any other's) stops working.
CREATE OR REPLACE FUNCTION public.rpc_bump_session_version() RETURNS integer
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE admins
  SET session_version = session_version + 1
  WHERE admin_id = public.current_admin_id()
  RETURNING session_version;
$$;

-- utils/security.py login_required's periodic check: is this session
-- still valid (not logged out elsewhere, not archived)?
CREATE OR REPLACE FUNCTION public.rpc_session_valid() RETURNS boolean
LANGUAGE sql STABLE
SET search_path = public
AS $$
  SELECT public.current_admin_id() IS NOT NULL;
$$;

REVOKE ALL ON FUNCTION public.rpc_bump_session_version() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.rpc_session_valid() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.rpc_bump_session_version() TO authenticated;
GRANT EXECUTE ON FUNCTION public.rpc_session_valid() TO authenticated;

COMMIT;


-- =========================================================================
-- 3. Login: case-insensitive username (TD-118), returns session_version,
-- and enforces the login throttle INSIDE the function (ADR-86).
--
-- The throttle has to live here, not in Flask: this function is granted to
-- anon, so anyone with the public anon key can call it directly and skip
-- any Flask-side check. Two limits, both counted in login_failures:
--   - 5 failures / 15 min per (client key, identifier). p_client_key is a
--     hash of the client IP that Flask passes in, so one person guessing
--     doesn't lock out other admins on the same library Wi-Fi.
--   - 20 failures / 15 min per identifier, whatever the client key. A
--     direct caller can invent client keys, so this per-account cap is
--     what actually bounds brute force. (Google sign-in still works while
--     an account is throttled.)
-- A throttled call returns one row with throttled = true and no identity.
-- =========================================================================

BEGIN;

DROP FUNCTION IF EXISTS public.rpc_login_lookup(text, text);
DROP FUNCTION IF EXISTS public.rpc_login_lookup(text, text, text);

CREATE OR REPLACE FUNCTION public.rpc_login_lookup(
  p_identifier text, p_password text, p_client_key text DEFAULT ''
)
RETURNS TABLE (admin_id integer, username text, status text, legacy_hash text,
               session_version integer, throttled boolean)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  row_rec admins%ROWTYPE;
  v_ident text := left(lower(coalesce(p_identifier, '')), 200);
  v_pair_key text := 'pair:' || left(coalesce(p_client_key, ''), 128) || '|' || v_ident;
  v_ident_key text := 'id:' || v_ident;
BEGIN
  DELETE FROM login_failures WHERE failed_at < now() - interval '1 day';

  IF (SELECT count(*) FROM login_failures
      WHERE key = v_pair_key AND failed_at > now() - interval '15 minutes') >= 5
     OR (SELECT count(*) FROM login_failures
         WHERE key = v_ident_key AND failed_at > now() - interval '15 minutes') >= 20 THEN
    RETURN QUERY SELECT NULL::integer, NULL::text, NULL::text, NULL::text, NULL::integer, true;
    RETURN;
  END IF;

  SELECT * INTO row_rec FROM admins a
  WHERE lower(a.username) = v_ident OR a.mobile = p_identifier
  LIMIT 1;

  IF FOUND AND row_rec.password NOT LIKE '$2%' THEN
    -- Legacy werkzeug hash: returned once so routes/auth.py can verify it
    -- in Python and upgrade it (unchanged from ADR-77). Python records the
    -- failure itself via rpc_record_login_failure() if it doesn't match.
    RETURN QUERY SELECT row_rec.admin_id, row_rec.username, row_rec.status,
                        row_rec.password, row_rec.session_version, false;
    RETURN;
  END IF;

  IF FOUND AND crypt(p_password, row_rec.password) = row_rec.password THEN
    DELETE FROM login_failures WHERE key IN (v_pair_key, v_ident_key);
    RETURN QUERY SELECT row_rec.admin_id, row_rec.username, row_rec.status,
                        NULL::text, row_rec.session_version, false;
    RETURN;
  END IF;

  -- Unknown identifier or wrong password: count it, return nothing.
  INSERT INTO login_failures (key) VALUES (v_pair_key), (v_ident_key);
  RETURN;
END;
$$;

REVOKE ALL ON FUNCTION public.rpc_login_lookup(text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.rpc_login_lookup(text, text, text) TO anon;

CREATE OR REPLACE FUNCTION public.rpc_register_admin(
  p_full_name text, p_username text, p_mobile text,
  p_email text, p_password_hash text
) RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  new_id integer;
BEGIN
  IF EXISTS (SELECT 1 FROM admins WHERE lower(username) = lower(p_username)) THEN
    RAISE EXCEPTION 'username_taken' USING ERRCODE = 'unique_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM admins WHERE mobile = p_mobile) THEN
    RAISE EXCEPTION 'mobile_taken' USING ERRCODE = 'unique_violation';
  END IF;
  INSERT INTO admins (full_name, username, mobile, email, password, role)
  VALUES (p_full_name, lower(p_username), p_mobile, p_email, p_password_hash, 'Admin')
  RETURNING admins.admin_id INTO new_id;
  RETURN new_id;
END;
$$;

REVOKE ALL ON FUNCTION public.rpc_register_admin(text, text, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.rpc_register_admin(text, text, text, text, text) TO anon;

COMMIT;


-- =========================================================================
-- 4. Google sign-in RPCs (ADR-84).
--
-- rpc_google_login_lookup / rpc_register_admin_google take their identity
-- ONLY from the caller's Supabase Auth JWT (auth.uid(), auth.jwt()), and
-- only accept a JWT whose sign-in provider list includes google - so an
-- email/password Supabase Auth user (if that provider were ever enabled)
-- can't use them. Flask's own tenant JWTs have no `sub`, so auth.uid() is
-- NULL for them and both functions return nothing / raise.
-- =========================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.rpc_google_login_lookup()
RETURNS TABLE (admin_id integer, username text, status text, session_version integer)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT a.admin_id, a.username, a.status, a.session_version
  FROM admins a
  WHERE auth.uid() IS NOT NULL
    AND (auth.jwt()->'app_metadata'->'providers') ? 'google'
    AND a.auth_user_id = auth.uid()
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.rpc_register_admin_google(
  p_full_name text, p_username text, p_mobile text
) RETURNS TABLE (admin_id integer, username text, status text, session_version integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_email text := auth.jwt()->>'email';
  new_id integer;
BEGIN
  IF v_uid IS NULL OR NOT ((auth.jwt()->'app_metadata'->'providers') ? 'google') THEN
    RAISE EXCEPTION 'not_google_user';
  END IF;
  IF EXISTS (SELECT 1 FROM admins WHERE auth_user_id = v_uid) THEN
    RAISE EXCEPTION 'google_already_linked' USING ERRCODE = 'unique_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM admins WHERE lower(admins.username) = lower(p_username)) THEN
    RAISE EXCEPTION 'username_taken' USING ERRCODE = 'unique_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM admins WHERE mobile = p_mobile) THEN
    RAISE EXCEPTION 'mobile_taken' USING ERRCODE = 'unique_violation';
  END IF;

  -- password: a random bcrypt hash nobody knows, so password login can
  -- never succeed until the admin sets one in Settings -> Security.
  INSERT INTO admins (full_name, username, mobile, email, password, role,
                      auth_user_id, google_email, has_password)
  VALUES (p_full_name, lower(p_username), p_mobile, v_email,
          crypt(gen_random_uuid()::text, gen_salt('bf')), 'Admin',
          v_uid, v_email, false)
  RETURNING admins.admin_id INTO new_id;

  RETURN QUERY SELECT a.admin_id, a.username, a.status, a.session_version
               FROM admins a WHERE a.admin_id = new_id;
END;
$$;

-- p_auth_user_id/p_email come from Flask, which got them from its own
-- server-side PKCE code exchange with Supabase Auth. Scoped by
-- current_admin_id(), so only a Flask-minted tenant JWT can call it, and
-- only for the logged-in admin's own row.
CREATE OR REPLACE FUNCTION public.rpc_link_google(p_auth_user_id uuid, p_email text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF public.current_admin_id() IS NULL THEN
    RAISE EXCEPTION 'not_logged_in';
  END IF;
  IF EXISTS (SELECT 1 FROM admins
             WHERE auth_user_id = p_auth_user_id
               AND admin_id <> public.current_admin_id()) THEN
    RAISE EXCEPTION 'google_already_linked' USING ERRCODE = 'unique_violation';
  END IF;
  UPDATE admins
  SET auth_user_id = p_auth_user_id, google_email = p_email
  WHERE admin_id = public.current_admin_id();
END;
$$;

-- Refuses to unlink a Google-only account (no password set yet) - that
-- would leave the admin with no way to sign in at all.
CREATE OR REPLACE FUNCTION public.rpc_unlink_google()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM admins
             WHERE admin_id = public.current_admin_id() AND has_password = false) THEN
    RAISE EXCEPTION 'no_password_set';
  END IF;
  UPDATE admins
  SET auth_user_id = NULL, google_email = NULL
  WHERE admin_id = public.current_admin_id();
END;
$$;

REVOKE ALL ON FUNCTION public.rpc_google_login_lookup() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.rpc_register_admin_google(text, text, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.rpc_link_google(uuid, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.rpc_unlink_google() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.rpc_google_login_lookup() TO authenticated;
GRANT EXECUTE ON FUNCTION public.rpc_register_admin_google(text, text, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.rpc_link_google(uuid, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.rpc_unlink_google() TO authenticated;

-- The insecure name+mobile reset path is gone (QA audit 2026-10-03).
DROP FUNCTION IF EXISTS public.rpc_forgot_password_lookup(text);
DROP FUNCTION IF EXISTS public.rpc_reset_password(integer, text, text, text);
DROP FUNCTION IF EXISTS public.rpc_reset_password(integer, text);

COMMIT;


